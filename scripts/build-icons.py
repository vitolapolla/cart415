"""Extracts the Material Symbols the app uses into public/icons.js.
Usage: python3 scripts/build-icons.py <path to @material-symbols/svg-400/rounded>"""
import os
import re
import sys

NAMES = {
    'home': 'home', 'home-fill': 'home-fill', 'search': 'search', 'explore': 'explore', 'explore-fill': 'explore-fill',
    'radio': 'radio', 'radio-fill': 'radio-fill', 'library': 'library_music', 'library-fill': 'library_music-fill',
    'kids': 'child_care', 'kids-fill': 'child_care-fill', 'plus': 'add', 'heart': 'favorite', 'heart-fill': 'favorite-fill',
    'settings': 'settings', 'close': 'close', 'play': 'play_arrow-fill', 'pause': 'pause-fill', 'prev': 'skip_previous-fill',
    'next': 'skip_next-fill', 'shuffle': 'shuffle', 'repeat': 'repeat', 'repeat-one': 'repeat_one', 'moon': 'bedtime',
    'lyrics': 'lyrics', 'queue': 'queue_music', 'speaker': 'speaker', 'phone': 'mobile', 'laptop': 'computer',
    'volume': 'volume_up', 'mute': 'volume_off', 'more': 'more_vert', 'play-next': 'queue_play_next', 'add-list': 'playlist_add',
    'user': 'person', 'trash': 'delete', 'edit': 'edit', 'external': 'open_in_new', 'refresh': 'refresh', 'link': 'link',
    'chevron-down': 'keyboard_arrow_down', 'chevron-right': 'chevron_right', 'cast': 'cast', 'check': 'check', 'live': 'sensors',
    'note': 'music_note', 'video': 'smart_display', 'tune': 'tune', 'history': 'history', 'trending': 'trending_up',
    'back': 'arrow_back', 'group': 'speaker_group', 'chart': 'leaderboard', 'info': 'info',
    'palette': 'palette', 'headphones': 'headphones', 'album': 'album', 'toys': 'toys', 'bed': 'crib', 'light': 'light_mode',
    'dark': 'dark_mode', 'dice': 'casino', 'key': 'key',
}

src = sys.argv[1]
lines = ['// Material Symbols (Rounded, weight 400), Apache License 2.0, from @material-symbols/svg-400.',
         '// Generated by scripts/build-icons.py. All paths use viewBox="0 -960 960 960".',
         'export const ICONS = {']
for key, name in NAMES.items():
    svg = open(os.path.join(src, name + '.svg')).read()
    lines.append(f"  '{key}': '{' '.join(re.findall(r' d=\"([^\"]+)\"', svg))}',")
lines.append('};\n')
out = os.path.join(os.path.dirname(__file__), '..', 'public', 'icons.js')
open(out, 'w').write('\n'.join(lines))
print(f'{len(NAMES)} icons → public/icons.js')
